"""Generate burned-caption data from vo/timing.json.

Vertical video is watched with the sound off, so a cut without captions is a
silent film. These come from the same word boundaries that time every animation,
so they cannot drift out of sync with the narration.

    python3 captions.py                       # writes src/shared/captions.ts
    python3 captions.py --words 3 --check      # preview the grouping, write nothing

Options:
    --words N     max words per card (default 4)
    --maxchars N  max characters per card (default 26)
    --gap F       seconds of silence that forces a new card (default 0.28)
    --check       print the cards instead of writing the module

Groups break on punctuation first, then on the word/character limits, then on
any real pause. Short groups that change on the beat hold the eye; a whole
sentence on screen at once does not.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path.cwd()


def main() -> None:
    a = sys.argv[1:]
    fl = {a[i]: a[i + 1] for i in range(len(a)) if a[i].startswith("--") and i + 1 < len(a)}
    max_words = int(fl.get("--words", 4))
    max_chars = int(fl.get("--maxchars", 26))
    gap = float(fl.get("--gap", 0.28))

    timing = json.loads((ROOT / "vo" / "timing.json").read_text())
    fps = timing["fps"]

    cards = []
    for bid in sorted(timing["beats"], key=int):
        beat = timing["beats"][bid]
        base = beat["start"]
        words = beat["words"]
        if not words:
            continue
        # Map each boundary word back to the punctuation in the narration.
        text_words = beat["narration"].split()
        cur: list[dict] = []

        def flush():
            if not cur:
                return
            start = base + cur[0]["t"]
            end = base + cur[-1]["t"] + cur[-1]["d"]
            cards.append({
                "text": " ".join(w["w"] for w in cur),
                "from": round(start * fps),
                "to": round(end * fps),
            })
            cur.clear()

        for i, w in enumerate(words):
            cur.append(w)
            joined = " ".join(x["w"] for x in cur)
            ends_clause = False
            if i < len(text_words):
                ends_clause = bool(re.search(r"[.,;:!?]$", text_words[min(i, len(text_words) - 1)]))
            nxt = words[i + 1] if i + 1 < len(words) else None
            pause = nxt is not None and (nxt["t"] - (w["t"] + w["d"])) > gap
            if ends_clause or pause or len(cur) >= max_words or len(joined) >= max_chars:
                flush()
        flush()

    # No card may outlast the next one's entrance.
    for i in range(len(cards) - 1):
        cards[i]["to"] = min(cards[i]["to"], cards[i + 1]["from"])

    if "--check" in a:
        print(f"  {len(cards)} cards @ {fps}fps\n")
        for c in cards:
            print(f"  {c['from']:>5}-{c['to']:<5} {c['text']}")
        return

    lines = [
        "// GENERATED by scripts/captions.py from vo/timing.json. Do not hand-edit.",
        "",
        "export type Caption = { text: string; from: number; to: number };",
        "",
        "export const CAPTIONS: Caption[] = [",
    ]
    for c in cards:
        safe = c["text"].replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'  {{ text: "{safe}", from: {c["from"]}, to: {c["to"]} }},')
    lines += ["];", ""]

    out = ROOT / "src" / "shared" / "captions.ts"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"  wrote {out}  ({len(cards)} cards)")


if __name__ == "__main__":
    main()
