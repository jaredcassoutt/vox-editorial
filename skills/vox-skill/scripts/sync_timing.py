"""Turn vo/timing.json + cues.json into a TypeScript timing module.

Hand-tuning thirty frame numbers against a waveform works exactly once. Change
the voice, the rate, or a single word of the script and every one of them is
wrong. This makes the timings derived data: name the *word* a beat should land
on, and the frame is recomputed on every re-voice.

    python3 sync_timing.py                 # reads ./cues.json, writes src/shared/timing.ts
    python3 sync_timing.py --check         # print the cue table, write nothing

cues.json:

    {
      "scenes": [
        {"name": "olderThanState", "beats": [1, 2]},
        {"name": "closer", "beats": [12], "tail": 30}
      ],
      "cues": {
        "s1.stamp":  {"beat": 2, "word": "chartered"},
        "s1.strike": {"beat": 2, "word": "exists", "offset": 2},
        "s4.baylorIn": {"beat": 6, "word": "Robert", "offset": -32},
        "s6.signEnd": {"scene": "signing", "fromEnd": 12}
      }
    }

A cue is one of:
  {"beat": N, "word": "w"}              frame the word is spoken, scene-local
  {"beat": N, "word": "w", "nth": 2}    the 2nd occurrence of that word
  {"beat": N, "word": "w", "offset": -32}   shifted, e.g. to start an entrance early
  {"beat": N, "start": true}            the beat's first frame, scene-local
  {"scene": "name", "fromEnd": 12}      counted back from the scene's last frame
  {"cue": "other.cue", "offset": 14}    relative to another cue

Scene duration runs from its first beat's start to the next scene's first beat's
start, so every cut lands in the gap between two spoken lines. The last scene
gets `tail` extra frames to hold on the final image.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path.cwd()


def norm(w: str) -> str:
    return re.sub(r"[^a-z0-9']", "", w.lower())


def main() -> None:
    check = "--check" in sys.argv
    timing = json.loads((ROOT / "vo" / "timing.json").read_text())
    spec = json.loads((ROOT / "cues.json").read_text())
    fps = timing["fps"]
    beats = timing["beats"]
    scenes = spec["scenes"]

    # Scene start/duration, straight off the beat windows.
    starts, durations = {}, {}
    for i, sc in enumerate(scenes):
        first = str(sc["beats"][0])
        start_f = round(beats[first]["start"] * fps)
        starts[sc["name"]] = start_f
        if i + 1 < len(scenes):
            end_f = round(beats[str(scenes[i + 1]["beats"][0])]["start"] * fps)
        else:
            end_f = timing["totalFrames"] + sc.get("tail", 30)
        durations[sc["name"]] = end_f - start_f

    beat_scene = {b: sc["name"] for sc in scenes for b in sc["beats"]}

    resolved: dict[str, int] = {}

    def resolve(name: str, c: dict, depth: int = 0) -> int:
        if depth > 8:
            raise ValueError(f"cue cycle at {name}")
        off = int(c.get("offset", 0))
        if "cue" in c:
            ref = c["cue"]
            if ref not in resolved:
                resolved[ref] = resolve(ref, spec["cues"][ref], depth + 1)
            return resolved[ref] + off
        if "scene" in c:
            return durations[c["scene"]] - int(c["fromEnd"]) + off
        b = str(c["beat"])
        sc = beat_scene[int(b)]
        base = round(beats[b]["start"] * fps) - starts[sc]
        if c.get("start"):
            return base + off
        want = norm(c["word"])
        hits = [w for w in beats[b]["words"] if norm(w["w"]) == want]
        if not hits:
            raise SystemExit(
                f"cue '{name}': no word '{c['word']}' in beat {b}\n"
                f"  beat text: {beats[b]['narration']}"
            )
        nth = int(c.get("nth", 1))
        if nth > len(hits):
            raise SystemExit(f"cue '{name}': only {len(hits)} of '{c['word']}' in beat {b}")
        return base + round(hits[nth - 1]["t"] * fps) + off

    for name, c in spec["cues"].items():
        if name not in resolved:
            resolved[name] = resolve(name, c)

    total = sum(durations.values())

    if check:
        print(f"  VO {timing['totalDuration']:.2f}s -> sequence {total} frames "
              f"({total/fps:.2f}s) @ {fps}fps\n")
        for sc in scenes:
            n = sc["name"]
            print(f"  {n:<18} beats {str(sc['beats']):<10} start {starts[n]:>5}  "
                  f"{durations[n]:>4}f  {durations[n]/fps:5.2f}s")
        print()
        for k in sorted(resolved):
            print(f"  {k:<26} {resolved[k]:>5}")
        return

    lines = [
        "// GENERATED by scripts/sync_timing.py from vo/timing.json + cues.json.",
        "// Do not hand-edit. Re-voice, then re-run the script.",
        "",
        f"export const FPS = {fps};",
        "",
        "/** Scene lengths, each running to the next scene's first spoken word. */",
        "export const D = {",
    ]
    for sc in scenes:
        n = sc["name"]
        first = str(sc["beats"][0])
        text = beats[first]["narration"][:52]
        lines.append(f'  {n}: {durations[n]}, // {durations[n]/fps:5.2f}s  "{text}..."')
    lines += [
        "} as const;",
        "",
        f"export const SEQUENCE_DURATION = {total};",
        "",
        "/** Frames each element lands on, scene-local, derived from word boundaries. */",
        "export const CUE = {",
    ]
    for k in sorted(resolved):
        lines.append(f'  "{k}": {resolved[k]},')
    lines += ["} as const;", ""]

    out = ROOT / "src" / "shared" / "timing.ts"
    out.write_text("\n".join(lines))
    print(f"  wrote {out}")
    print(f"  {len(scenes)} scenes, {len(resolved)} cues, {total} frames ({total/fps:.2f}s)")


if __name__ == "__main__":
    main()
